def defense_qa_markdown() -> str:
    """答辩问答置于讲稿末尾，不新增幻灯片或逐页口播章节。"""
    parts = ["## 答辩问题与参考回答（讲稿末尾，不加入PPT）", "", "供提问环节备查。", ""]
    for number, (question, answer, source) in enumerate(DEFENSE_QA, 1):
        parts.extend(
            [f"### 问题{number:02}：{question}", "", f"答：{answer}", "", f"依据：{source}", ""]
        )
    return "\n".join(parts)
